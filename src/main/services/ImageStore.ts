/**
 * Where image bytes live.
 *
 * A message carries a `MessageImage` reference; the bytes are here, in a
 * directory per conversation, named by the image id. The split exists because
 * a conversation file is read and parsed whole on every `get()` — which
 * `update()` does before every write — and the renderer holds a bounded
 * window of messages in memory. A screenshot is one to three megabytes of
 * base64; inlining that into the transcript would undo the bounding on every
 * save and make every read of the conversation pay for it.
 *
 * Images arrive from two directions and both are untrusted input: a tool
 * result relays bytes the model's tools produced, and the composer relays
 * whatever the user pasted. So the media type is checked against the four the
 * Anthropic API accepts, the size is capped, and the id is generated here
 * rather than taken from a caller — an id that reached the filesystem could
 * otherwise name a path.
 */

import fs from 'node:fs';
import path from 'node:path';

import { generateId, ID_PREFIXES } from '../../shared/id';
import {
  IMAGE_MEDIA_TYPES, type ImageMediaType, type MessageImage,
} from '../../shared/types';
import logger from '../utils/logger';
import { getConversationsPath, isPathWithin } from '../utils/paths';

/**
 * The largest image we will store, in bytes of decoded image data.
 *
 * The API's own per-image ceiling is 5 MB, and anything larger is rejected
 * there — storing it would only move the failure later, after the user has
 * waited for a turn. Checked on the decoded size, not the base64 text, which
 * is a third larger.
 */
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

/** File extension per accepted media type. */
const EXTENSIONS: Record<ImageMediaType, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/gif': 'gif',
  'image/webp': 'webp',
};

export class ImageStore {
  private readonly root: string;

  constructor(root?: string) {
    this.root = root ?? path.join(getConversationsPath(), 'images');
  }

  /**
   * The directory holding one conversation's images.
   *
   * The conversation id reaches the filesystem, so it is sanitised the same
   * way `ConversationService.getFilePath` sanitises it, and the result is
   * checked to be inside the root before anything is written.
   */
  private dirFor(conversationId: string): string {
    const safe = conversationId.replace(/[^a-zA-Z0-9_-]/g, '_');
    const dir = path.join(this.root, safe);
    if (!isPathWithin(dir, this.root)) {
      throw new Error('Invalid conversation ID: path traversal detected');
    }
    return dir;
  }

  private fileFor(conversationId: string, image: { id: string; mediaType: ImageMediaType }): string {
    // The id is generated by `save`, never supplied, but it is about to be a
    // path segment either way — so it is checked rather than trusted.
    if (!/^[A-Za-z0-9_-]+$/.test(image.id)) {
      throw new Error('Invalid image ID');
    }
    return path.join(this.dirFor(conversationId), `${image.id}.${EXTENSIONS[image.mediaType]}`);
  }

  /**
   * Store bytes and return the reference a message should carry.
   *
   * Returns null rather than throwing when the input is not something we
   * accept: an unsupported media type or an oversized image is a fact about
   * the data, not a failure of the app, and the caller's job is to carry on
   * without the image rather than to lose the message it came with.
   */
  async save(
    conversationId: string,
    input: {
      base64: string;
      mediaType: string;
      origin: MessageImage['origin'];
      label?: string;
      width?: number;
      height?: number;
    },
  ): Promise<MessageImage | null> {
    if (!isImageMediaType(input.mediaType)) {
      logger.warn('Refused an image with an unsupported media type', {
        conversationId, mediaType: input.mediaType,
      });
      return null;
    }

    let bytes: Buffer;
    try {
      bytes = Buffer.from(input.base64, 'base64');
    } catch (error) {
      logger.warn('Refused an image whose data would not decode', { conversationId, error });
      return null;
    }
    if (bytes.length === 0) {
      logger.warn('Refused an empty image', { conversationId });
      return null;
    }
    if (bytes.length > MAX_IMAGE_BYTES) {
      logger.warn('Refused an image over the size limit', {
        conversationId, byteSize: bytes.length, limit: MAX_IMAGE_BYTES,
      });
      return null;
    }

    const image: MessageImage = {
      id: generateId(ID_PREFIXES.IMAGE),
      mediaType: input.mediaType,
      byteSize: bytes.length,
      origin: input.origin,
      ...(input.label ? { label: input.label } : {}),
      ...(input.width ? { width: input.width } : {}),
      ...(input.height ? { height: input.height } : {}),
    };

    const dir = this.dirFor(conversationId);
    await fs.promises.mkdir(dir, { recursive: true });
    await fs.promises.writeFile(this.fileFor(conversationId, image), bytes);

    logger.info('Stored an image', {
      conversationId, id: image.id, mediaType: image.mediaType, byteSize: image.byteSize,
    });
    return image;
  }

  /**
   * Read bytes back for display. Null when there are none — an image whose
   * file is missing is a gap in the transcript, not a reason to fail the
   * conversation around it.
   */
  async read(
    conversationId: string,
    id: string,
    mediaType: string,
  ): Promise<{ base64: string; mediaType: ImageMediaType } | null> {
    if (!isImageMediaType(mediaType)) return null;
    try {
      const bytes = await fs.promises.readFile(this.fileFor(conversationId, { id, mediaType }));
      return { base64: bytes.toString('base64'), mediaType };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
        logger.warn('No stored bytes for an image', { conversationId, id });
        return null;
      }
      logger.error('Failed to read a stored image', { conversationId, id, error });
      throw error;
    }
  }

  /**
   * Drop every image a conversation owns.
   *
   * Called when the conversation is deleted. Without it the bytes outlive the
   * transcript that referenced them, and nothing would ever name them again —
   * an unbounded leak of the largest files this app writes.
   */
  async deleteAll(conversationId: string): Promise<void> {
    try {
      await fs.promises.rm(this.dirFor(conversationId), { recursive: true, force: true });
    } catch (error) {
      logger.warn('Failed to remove a conversation image directory', { conversationId, error });
    }
  }
}

export function isImageMediaType(value: string): value is ImageMediaType {
  return (IMAGE_MEDIA_TYPES as readonly string[]).includes(value);
}
